def get_team_full_name(abbreviation: str) -> str:
    """
    Get a team's full name from its abbreviation.

    Args:
        abbreviation (str): Team abbreviation (e.g., 'lal')

    Returns:
        str: Full team name in URL format (e.g., 'los-angeles-lakers')

    Raises:
        KeyError: If team abbreviation is not found
    """
    try:
        return NBA_TEAMS[abbreviation.lower()]['full_name']
    except KeyError:
        raise KeyError(f"Unknown team abbreviation: {abbreviation}")

def get_teams_by_conference(conference: str) -> list:
    """
    Get all teams in a specific conference.

    Args:
        conference (str): Conference name ('Eastern' or 'Western')

    Returns:
        list: List of team dictionaries in the specified conference
    """
    return [team for team in NBA_TEAMS.values() if team['conference'] == conference]

def get_teams_by_division(division: str) -> list:
    """
    Get all teams in a specific division.

    Args:
        division (str): Division name (e.g., 'Pacific', 'Atlantic')

    Returns:
        list: List of team dictionaries in the specified division
    """
    return [team for team in NBA_TEAMS.values() if team['division'] == division]
